"""ui.builders.humanego — extracted application responsibilities."""
from __future__ import annotations
from eai_app.paths import PROJECT_ROOT
from eai_app.infrastructure.module_ref import module_ref
_eai_adapters_models_bagel_launchers = module_ref('eai_app.adapters.models.bagel_launchers')
_eai_configuration_models = module_ref('eai_app.configuration.models')
_eai_configuration_policies = module_ref('eai_app.configuration.policies')
_eai_configuration_tabs = module_ref('eai_app.configuration.tabs')
_eai_platform_bootstrap = module_ref('eai_app.platform.bootstrap')
_eai_ui_widgets_inputs = module_ref('eai_app.ui.widgets.inputs')

def build(self, build):
    humanego_tab = _eai_platform_bootstrap.QWidget()
    humanego_tab.setObjectName("humanegoTab")
    humanego_outer = _eai_platform_bootstrap.QVBoxLayout(humanego_tab)
    humanego_outer.setContentsMargins(8, 6, 8, 6)
    humanego_outer.setSpacing(6)
    humanego_hint = _eai_platform_bootstrap.QLabel(
        "HumanEgo（"
        f"{_eai_configuration_models.HUMANOGO_ROOT_DEFAULT}"
        "）：在仓库目录中运行 setup / 下载 / 预处理 / 训练。需先 "
        "`conda create -n humanego python=3.11 && bash setup.sh`。"
    )
    humanego_hint.setWordWrap(True)
    humanego_hint.setStyleSheet(f"color: {_eai_configuration_policies.UI_TEXT_MUTED};")
    humanego_outer.addWidget(humanego_hint)

    he_path_row = _eai_platform_bootstrap.QHBoxLayout()
    he_path_row.setSpacing(6)
    he_path_row.addWidget(_eai_platform_bootstrap.QLabel("仓库"))
    self.humanego_root_edit = _eai_platform_bootstrap.QLineEdit(
        _eai_platform_bootstrap.os.environ.get("HUMANOGO_DIR", _eai_configuration_models.HUMANOGO_ROOT_DEFAULT)
    )
    self.humanego_root_edit.setFont(_eai_platform_bootstrap.QFont(_eai_configuration_policies.UI_MONO_FAMILY, _eai_configuration_policies.UI_MONO_SIZE_SMALL))
    he_path_row.addWidget(self.humanego_root_edit, 1)
    self.humanego_root_browse_btn = _eai_platform_bootstrap.QPushButton("…")
    self.humanego_root_browse_btn.setFixedWidth(28)
    self.humanego_root_browse_btn.clicked.connect(self._on_humanego_root_browse)
    he_path_row.addWidget(self.humanego_root_browse_btn)
    he_path_row.addWidget(_eai_platform_bootstrap.QLabel("Python"))
    self.humanego_python_edit = _eai_platform_bootstrap.QLineEdit(
        _eai_configuration_tabs.resolve_humanego_python(self.humanego_root_edit.text())
    )
    self.humanego_python_edit.setFont(_eai_platform_bootstrap.QFont(_eai_configuration_policies.UI_MONO_FAMILY, _eai_configuration_policies.UI_MONO_SIZE_SMALL))
    he_path_row.addWidget(self.humanego_python_edit, 1)
    self.humanego_python_browse_btn = _eai_platform_bootstrap.QPushButton("…")
    self.humanego_python_browse_btn.setFixedWidth(28)
    self.humanego_python_browse_btn.clicked.connect(self._on_humanego_python_browse)
    he_path_row.addWidget(self.humanego_python_browse_btn)
    humanego_outer.addLayout(he_path_row)

    he_run_row = _eai_platform_bootstrap.QHBoxLayout()
    he_run_row.setSpacing(6)
    he_run_row.addWidget(_eai_platform_bootstrap.QLabel("动作"))
    self.humanego_action_combo = _eai_ui_widgets_inputs.ImeSafeComboBox()
    self.humanego_action_combo.addItem("下载数据 (download)", "download")
    self.humanego_action_combo.addItem("预处理 (preprocess)", "preprocess")
    self.humanego_action_combo.addItem("训练 (train)", "train")
    self.humanego_action_combo.addItem("环境安装 (setup.sh)", "setup")
    self.humanego_action_combo.addItem("自定义命令", "custom")
    self.humanego_action_combo.currentIndexChanged.connect(
        self._on_humanego_action_changed
    )
    he_run_row.addWidget(self.humanego_action_combo)
    he_run_row.addWidget(_eai_platform_bootstrap.QLabel("task"))
    self.humanego_task_combo = _eai_ui_widgets_inputs.ImeSafeComboBox()
    self.humanego_task_combo.addItem("serve_bread", "serve_bread")
    self.humanego_task_combo.addItem("water_flowers", "water_flowers")
    self.humanego_task_combo.addItem("all", "all")
    self.humanego_task_combo.currentIndexChanged.connect(
        self._on_humanego_action_changed
    )
    he_run_row.addWidget(self.humanego_task_combo)
    he_run_row.addWidget(_eai_platform_bootstrap.QLabel("num"))
    self.humanego_num_edit = _eai_platform_bootstrap.QLineEdit("2")
    self.humanego_num_edit.setFixedWidth(48)
    self.humanego_num_edit.setToolTip("download 的 --num（数字或 all）")
    self.humanego_num_edit.editingFinished.connect(self._on_humanego_action_changed)
    he_run_row.addWidget(self.humanego_num_edit)
    self.humanego_input_only_check = _eai_platform_bootstrap.QCheckBox("input-only")
    self.humanego_input_only_check.setChecked(True)
    self.humanego_input_only_check.setToolTip("download 时只下输入，自行跑预处理")
    self.humanego_input_only_check.toggled.connect(self._on_humanego_action_changed)
    he_run_row.addWidget(self.humanego_input_only_check)
    self.humanego_use_cfg_check = _eai_platform_bootstrap.QCheckBox("use_cfg")
    self.humanego_use_cfg_check.setChecked(True)
    self.humanego_use_cfg_check.setToolTip("训练时加 --use_cfg")
    self.humanego_use_cfg_check.toggled.connect(self._on_humanego_action_changed)
    he_run_row.addWidget(self.humanego_use_cfg_check)
    he_run_row.addStretch(1)
    humanego_outer.addLayout(he_run_row)

    he_mps_row = _eai_platform_bootstrap.QHBoxLayout()
    he_mps_row.setSpacing(6)
    he_mps_row.addWidget(_eai_platform_bootstrap.QLabel("mps_path"))
    self.humanego_mps_edit = _eai_platform_bootstrap.QLineEdit()
    self.humanego_mps_edit.setPlaceholderText(
        "预处理用：./data/serve_bread/aria/mps_serve_bread_000_vrs"
    )
    self.humanego_mps_edit.setFont(_eai_platform_bootstrap.QFont(_eai_configuration_policies.UI_MONO_FAMILY, _eai_configuration_policies.UI_MONO_SIZE_SMALL))
    self.humanego_mps_edit.textChanged.connect(self._on_humanego_action_changed)
    he_mps_row.addWidget(self.humanego_mps_edit, 1)
    self.humanego_mps_browse_btn = _eai_platform_bootstrap.QPushButton("…")
    self.humanego_mps_browse_btn.setFixedWidth(28)
    self.humanego_mps_browse_btn.clicked.connect(self._on_humanego_mps_browse)
    he_mps_row.addWidget(self.humanego_mps_browse_btn)
    self.humanego_refresh_mps_btn = _eai_platform_bootstrap.QPushButton("扫描 data/")
    self.humanego_refresh_mps_btn.setToolTip("扫描仓库 data/*/aria/mps_* 填入下拉")
    self.humanego_refresh_mps_btn.clicked.connect(self._on_humanego_refresh_mps)
    he_mps_row.addWidget(self.humanego_refresh_mps_btn)
    self.humanego_mps_combo = _eai_ui_widgets_inputs.ImeSafeComboBox()
    self.humanego_mps_combo.setMinimumWidth(180)
    self.humanego_mps_combo.setToolTip("选择已下载的 recording")
    self.humanego_mps_combo.currentIndexChanged.connect(
        self._on_humanego_mps_combo_changed
    )
    he_mps_row.addWidget(self.humanego_mps_combo)
    humanego_outer.addLayout(he_mps_row)

    he_cmd_row = _eai_platform_bootstrap.QHBoxLayout()
    he_cmd_row.setSpacing(6)
    he_cmd_row.addWidget(_eai_platform_bootstrap.QLabel("命令"))
    self.humanego_cmd_edit = _eai_ui_widgets_inputs.ImeSafeLineEdit("")
    self.humanego_cmd_edit.setFont(_eai_platform_bootstrap.QFont(_eai_configuration_policies.UI_MONO_FAMILY, _eai_configuration_policies.UI_MONO_SIZE_SMALL))
    self.humanego_cmd_edit.setPlaceholderText("将按动作自动生成，也可改成自定义命令")
    he_cmd_row.addWidget(self.humanego_cmd_edit, 1)
    humanego_outer.addLayout(he_cmd_row)

    he_btn_row = _eai_platform_bootstrap.QHBoxLayout()
    he_btn_row.setSpacing(6)
    self.humanego_status_label = _eai_platform_bootstrap.QLabel("HumanEgo: 空闲")
    self.humanego_status_label.setFont(_eai_platform_bootstrap.QFont(_eai_configuration_policies.UI_MONO_FAMILY, _eai_configuration_policies.UI_MONO_SIZE_SMALL))
    he_btn_row.addWidget(self.humanego_status_label, 1)
    self.humanego_run_btn = _eai_platform_bootstrap.QPushButton("运行")
    self.humanego_run_btn.clicked.connect(self._on_humanego_run_clicked)
    he_btn_row.addWidget(self.humanego_run_btn)
    self.humanego_stop_btn = _eai_platform_bootstrap.QPushButton("停止")
    self.humanego_stop_btn.setObjectName("dangerAction")
    self.humanego_stop_btn.setEnabled(False)
    self.humanego_stop_btn.clicked.connect(self._on_humanego_stop_clicked)
    he_btn_row.addWidget(self.humanego_stop_btn)
    self.humanego_clear_log_btn = _eai_platform_bootstrap.QPushButton("清空日志")
    self.humanego_clear_log_btn.clicked.connect(
        lambda: self.humanego_log_edit.clear()
    )
    he_btn_row.addWidget(self.humanego_clear_log_btn)
    self.humanego_web_btn = _eai_platform_bootstrap.QPushButton("项目主页")
    self.humanego_web_btn.clicked.connect(
        lambda: _eai_platform_bootstrap.QDesktopServices.openUrl(_eai_platform_bootstrap.QUrl(_eai_configuration_models.HUMANOGO_WEBSITE_URL))
    )
    he_btn_row.addWidget(self.humanego_web_btn)
    self.humanego_gallery_btn = _eai_platform_bootstrap.QPushButton("Data Gallery")
    self.humanego_gallery_btn.clicked.connect(
        lambda: _eai_platform_bootstrap.QDesktopServices.openUrl(_eai_platform_bootstrap.QUrl(_eai_configuration_models.HUMANOGO_GALLERY_URL))
    )
    he_btn_row.addWidget(self.humanego_gallery_btn)
    self.humanego_open_dir_btn = _eai_platform_bootstrap.QPushButton("打开目录")
    self.humanego_open_dir_btn.clicked.connect(self._on_humanego_open_dir)
    he_btn_row.addWidget(self.humanego_open_dir_btn)
    humanego_outer.addLayout(he_btn_row)

    self.humanego_log_edit = _eai_platform_bootstrap.QTextEdit()
    self.humanego_log_edit.setReadOnly(True)
    self.humanego_log_edit.setFont(_eai_platform_bootstrap.QFont(_eai_configuration_policies.UI_MONO_FAMILY, _eai_configuration_policies.UI_MONO_SIZE_SMALL))
    self.humanego_log_edit.setMinimumHeight(240)
    self.humanego_log_edit.setPlaceholderText("HumanEgo 运行日志…")
    self.humanego_log_edit.setStyleSheet(
        f"QTextEdit {{ color: {_eai_configuration_policies.UI_TEXT_PRIMARY}; background-color: {_eai_configuration_policies.UI_BG_LOG}; "
        f"border: 1px solid {_eai_configuration_policies.UI_BORDER}; }}"
    )
    humanego_outer.addWidget(self.humanego_log_edit, 1)

    self._humanego_launcher = _eai_adapters_models_bagel_launchers.HumanEgoLauncher(self)
    self._humanego_launcher.log_line.connect(self._append_humanego_log)
    self._humanego_launcher.status_message.connect(self._on_humanego_status)
    self._humanego_launcher.running_changed.connect(self._update_humanego_ui)
    self._on_humanego_action_changed()
    self._on_humanego_refresh_mps()
    build.control_tabs.addTab(humanego_tab, "HumanEgo")
