#!/usr/bin/env bash
# 让宿主机可以直接 ros2 topic 读取 Docker 内相机图像（无需 run_in_docker）。
#
# 根因: 容器内 FastDDS 用 128MB SHM 发图，段文件属主 root、权限 644，
#       宿主机用户无法加入 SHM → 能发现 topic 但收不到帧。
#
# 本脚本:
#   1) 补齐容器内缺失的 /etc/dds/fastdds_profiles_tele.xml
#   2) chmod a+rw /dev/shm/fastrtps_*（并后台保持）
#   3) 写出宿主机环境文件，供 run_local / 当前 shell source
#
# 用法:
#   bash scripts/enable_host_ros2_camera.sh
#   bash scripts/enable_host_ros2_camera.sh --stop-chmod
#   source /share_data/.../eai/.cache/host_ros2_camera.env
#   ros2 topic hz /camera/head_color
set -eo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
EAI_DIR="$(cd "${SCRIPT_DIR}/.." && pwd -P)"
CONTAINER="${A2D_DOCKER_CONTAINER:-a2d-tele-release-2-1-0rc3-latest}"
TELE_XML_HOST="${EAI_DIR}/dds/fastdds_profiles_tele.xml"
A2D_XML_HOST="${EAI_DIR}/dds/fastdds_profiles_a2d.xml"
CACHE_DIR="${EAI_DIR}/.cache"
ENV_FILE="${CACHE_DIR}/host_ros2_camera.env"
CHMOD_PID_FILE="${CACHE_DIR}/shm_chmod.docker.pid"

mkdir -p "${CACHE_DIR}"

if [[ "${1:-}" == "--stop-chmod" || "${1:-}" == "stop" ]]; then
    if [[ -f "${CHMOD_PID_FILE}" ]]; then
        old="$(cat "${CHMOD_PID_FILE}" 2>/dev/null || true)"
        [[ -n "${old}" ]] && docker exec "${CONTAINER}" bash -lc "kill ${old} 2>/dev/null || true" || true
        rm -f "${CHMOD_PID_FILE}"
    fi
    docker exec "${CONTAINER}" bash -lc "pkill -f 'eai_shm_chmod_loop' 2>/dev/null || true" || true
    echo ">>> 已停止 SHM chmod 循环"
    exit 0
fi

if ! command -v docker >/dev/null 2>&1; then
    echo "错误: 需要 docker" >&2
    exit 1
fi
if ! docker inspect "${CONTAINER}" >/dev/null 2>&1; then
    echo "错误: 容器不存在: ${CONTAINER}" >&2
    exit 1
fi
if [[ ! -f "${TELE_XML_HOST}" ]]; then
    echo "错误: 缺少 ${TELE_XML_HOST}" >&2
    exit 1
fi

echo ">>> 安装 DDS 配置到容器 ${CONTAINER}"
# 容器期望 tele.xml；同时刷新 a2d.xml 保持一致
docker exec "${CONTAINER}" mkdir -p /etc/dds
docker cp "${TELE_XML_HOST}" "${CONTAINER}:/etc/dds/fastdds_profiles_tele.xml"
if [[ -f "${A2D_XML_HOST}" ]]; then
    docker cp "${A2D_XML_HOST}" "${CONTAINER}:/etc/dds/fastdds_profiles_a2d.xml"
fi
docker exec "${CONTAINER}" bash -lc \
    "ls -la /etc/dds/fastdds_profiles_tele.xml /etc/dds/fastdds_profiles_a2d.xml"

echo ">>> 开放 /dev/shm/fastrtps_* 权限（宿主机加入 SHM）"
docker exec "${CONTAINER}" bash -lc "chmod a+rw /dev/shm/fastrtps_* 2>/dev/null || true"

# 后台循环：新创建的 SHM 段也改成 a+rw
docker exec "${CONTAINER}" bash -lc "pkill -f 'eai_shm_chmod_loop' 2>/dev/null || true" || true
CHMOD_PID="$(
docker exec "${CONTAINER}" bash -lc "
nohup bash -c '
# eai_shm_chmod_loop
while true; do
  chmod a+rw /dev/shm/fastrtps_* 2>/dev/null || true
  sleep 2
done
' >/tmp/eai_shm_chmod_loop.log 2>&1 &
echo \$!
"
)"
CHMOD_PID="$(echo "${CHMOD_PID}" | tr -dc '0-9\n' | tail -n 1)"
echo "${CHMOD_PID}" > "${CHMOD_PID_FILE}"
echo ">>> SHM chmod 循环已启动 (container pid=${CHMOD_PID})"

# 宿主机环境：Domain/RMW 对齐；DDS 用 SHM+UDP（收相机走 SHM，发手令走 UDP）
SHM_UDP_HOST="${EAI_DIR}/dds/fastdds_profiles_shm_udp.xml"
if [[ -f "${SHM_UDP_HOST}" ]]; then
    HOST_DDS="${SHM_UDP_HOST}"
    docker cp "${SHM_UDP_HOST}" "${CONTAINER}:/etc/dds/fastdds_profiles_shm_udp.xml" >/dev/null || true
else
    HOST_DDS="${TELE_XML_HOST}"
fi
cat > "${ENV_FILE}" <<EOF
# Generated by enable_host_ros2_camera.sh — source 后可用 ros2 直接收 /camera/*
# 手部命令需 SHM+UDP，否则宿主机 pub 进不了容器内 ruiyan
export RMW_IMPLEMENTATION=rmw_fastrtps_cpp
export ROS_DOMAIN_ID=0
export ROS_LOCALHOST_ONLY=1
unset ROS_AUTOMATIC_DISCOVERY_RANGE
export FASTRTPS_DEFAULT_PROFILES_FILE=${HOST_DDS}
EOF

echo ">>> 已写入宿主机环境: ${ENV_FILE}"
echo ">>> 验证中…"

# shellcheck disable=SC1090
set +u
# shellcheck disable=SC1091
source /opt/ros/humble/setup.bash
set -u
# shellcheck disable=SC1090
source "${ENV_FILE}"
ros2 daemon stop >/dev/null 2>&1 || true
sleep 1

if timeout 8 ros2 topic hz /camera/head_color 2>&1 | tee /tmp/eai_host_cam_hz.txt | grep -q "average rate"; then
    rate="$(grep -m1 "average rate" /tmp/eai_host_cam_hz.txt || true)"
    echo ">>> ✅ 宿主机可直接读取图像: ${rate}"
else
    echo ">>> ⚠️  暂未刷到 hz。若相机刚启动，等几秒后执行:" >&2
    echo "       source ${ENV_FILE} && ros2 topic hz /camera/head_color" >&2
    echo "       若仍失败: 重启容器内相机/机器人栈后再跑本脚本" >&2
fi

echo
echo "用法:"
echo "  source ${ENV_FILE}"
echo "  ros2 topic hz /camera/head_color"
echo "  cd ${EAI_DIR} && bash run_local.sh   # 已自动对齐 Domain/RMW/DDS"
